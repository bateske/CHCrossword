"""Build and run the host tests (the puzzle decoder, the rules, saving).

    python tools/tests/run_tests.py

The built-in puzzles are decoded with the Python reference decoder
(tools/puzzles/cwformat.py) into build/expect.h, which the C++ tests hold
the game's own decoder to.
"""
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE.parent / "chsim"))
sys.path.insert(0, str(HERE.parent / "puzzles"))
from chsim import find_cxx  # noqa: E402
import cwformat as cw  # noqa: E402

# The pure-logic sources, compiled beside the tests as they are.
SOURCES = [HERE / "test_crossword.cpp", ROOT / "src" / "game" / "Puzzle.cpp", ROOT / "src" / "game" / "Game.cpp",
           ROOT / "src" / "game" / "PuzzleData.cpp", ROOT / "src" / "pack" / "Pack.cpp"]


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def builtin_pack():
    """The BUILTIN array out of the generated PuzzleData.cpp."""
    text = (ROOT / "src" / "game" / "PuzzleData.cpp").read_text()
    body = text[text.index("BUILTIN["):]
    body = body[body.index("{") + 1:body.index("}")]
    return bytes(int(v) for v in body.replace("\n", " ").split(",") if v.strip())


def write_expect(path):
    _, blobs = cw.read_pack(builtin_pack())
    out = ["// Generated by run_tests.py from the reference decoder.", "static const std::vector<XPuzzle> EXPECT = {"]
    for blob in blobs:
        p = cw.decode(blob)
        n = len(p["grid"])
        across, down = cw.numbering(p["grid"])
        words = [(num, r * n + c, ln, 0, p["across"][num]) for num, r, c, ln in across]
        words += [(num, r * n + c, ln, 1, p["down"][num]) for num, r, c, ln in down]
        out.append(f"  {{{c_str(p['title'])}, {n}, {p['difficulty']}, {c_str(''.join(p['grid']))}, {{")
        out += [f"    {{{num}, {start}, {ln}, {d}, {c_str(clue)}}}," for num, start, ln, d, clue in words]
        out.append("  }},")
    out.append("};")
    path.write_text("\n".join(out) + "\n")


def main():
    exe = HERE / "build" / "test_crossword.exe"
    exe.parent.mkdir(exist_ok=True)
    write_expect(HERE / "build" / "expect.h")
    cmd = find_cxx() + ["-std=gnu++17", "-O2", "-Wall", "-Wextra", "-Wno-unused-parameter",
                        "-Wno-unused-function", "-Wno-unused-variable", "-Wno-unknown-pragmas",
                        "-fsanitize=undefined", "-fno-sanitize-recover=undefined",
                        "-DCHTEST", *[str(s) for s in SOURCES], "-o", str(exe)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit("build failed")
    if r.stderr.strip():
        sys.stderr.write(r.stderr)
    raise SystemExit(subprocess.run([str(exe), *sys.argv[1:]]).returncode)


if __name__ == "__main__":
    main()
